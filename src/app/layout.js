import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import LayoutWrapper from "@/components/shared/LayoutWrapper";
import { AuthProvider } from "@/components/shared/AuthProvider";
import { doc, getDoc } from "firebase/firestore";
import { db } from "@/components/lib/firebase";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export async function generateMetadata() {
  try {
    const snapshot = await getDoc(doc(db, "siteSettings", "general"));

    const seo = snapshot.exists() ? snapshot.data()?.seo : null;

    return {
      title: seo?.metaTitle || "Ekhalo",
      description: seo?.metaDescription || "Generated by Ekhalo",
      keywords: seo?.keywords
        ? seo.keywords.split(",").map((item) => item.trim())
        : [],

      alternates: {
        canonical: seo?.canonicalUrl || undefined,
      },

      openGraph: {
        title: seo?.metaTitle || "Ekhalo",
        description: seo?.metaDescription || "Generated by Ekhalo",
        type: "website",
      },
    };
  } catch (error) {
    console.error("SEO metadata error:", error);

    return {
      title: "Ekhalo",
      description: "Generated by Ekhalo",
    };
  }
}
